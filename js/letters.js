const gcd = (a, b) => b ? gcd(b, a % b) : a;
const unit = ([[x1, y1], [x2, y2]]) => {
  const n = gcd(Math.abs(x2 - x1), Math.abs(y2 - y1));
  const at = i => [x1 + (x2 - x1) * i / n, y1 + (y2 - y1) * i / n];
  return Array.from({ length: n }, (_, i) => [at(i), at(i + 1)]);
};

export const segKey = ([a, b]) => [a + '', b + ''].sort().join('|');
const dedupe = ss => [...new Map(ss.map(s => [segKey(s), s])).values()];
export const segs = strokes => dedupe(strokes.flatMap(s => s.slice(1).flatMap((p, i) => unit([s[i], p]))));
export const sig = ss => ss.map(segKey).sort().join(' ');

export const known = Object.fromEntries(Object.entries(letters).map(([c, s]) => [sig(segs(s)), c]));
export const every = dedupe(Object.values(letters).flatMap(s => segs(s)));
export const allowed = new Set(every.map(segKey));
